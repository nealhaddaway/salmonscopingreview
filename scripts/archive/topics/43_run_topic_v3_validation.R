# =============================================================================
# File: scripts/43_run_topic_v3_validation.R
# Purpose: Blindly classify the 50 manually coded validation records using
#          the frozen topic ontology v3.
#
# This script:
# - makes 50 low-cost API calls using gpt-5-mini;
# - never includes the human codes in the prompt;
# - checkpoints after every record;
# - can be stopped and safely resumed;
# - does not touch the previous full-corpus topic run.
# =============================================================================


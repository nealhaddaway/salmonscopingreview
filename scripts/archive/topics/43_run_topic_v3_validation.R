  )
}

ontology <- readr::read_csv(
  ontology_file,
  show_col_types = FALSE
)

records <- readr::read_csv(
  gold_file,
  show_col_types = FALSE
) |>
  dplyr::mutate(
    record_id = as.character(record_id),
    title = dplyr::coalesce(
      as.character(title),
      ""
    ),
    abstract = dplyr::coalesce(
      as.character(abstract),
      ""
    )
  ) |>
  # Human codes are deliberately removed before classification.
  dplyr::select(
    sampling_stratum,
    record_sequence,
    record_id,
    title,
    abstract
  )

required_ontology_columns <- c(
  "path_id",
  "hierarchy_path",
  "definition",
  "include_when",
  "exclude_when",

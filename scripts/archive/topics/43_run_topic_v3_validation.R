if (anyDuplicated(ontology$path_id) > 0L) {
  stop("Duplicate path_id values found in the ontology.")
}

if (anyDuplicated(ontology$hierarchy_path) > 0L) {
  stop("Duplicate hierarchy_path values found in the ontology.")
}

ontology_lines <- ontology |>
  dplyr::transmute(
    prompt_entry = paste0(
      path_id,
      " | ",
      hierarchy_path,
      "\nDefinition: ",
      definition,
      "\nInclude when: ",
      include_when,
      "\nExclude when: ",
      exclude_when,
      "\nExamples: ",
      examples
    )
  ) |>
  dplyr::pull(prompt_entry)

ontology_prompt <- paste(
  ontology_lines,
  collapse = "\n\n"
)


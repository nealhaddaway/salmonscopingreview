  ontology_prompt,
  ontology_prompt_file
)

response_schema <- list(
  type = "object",
  properties = list(
    assignments = list(
      type = "array",
      items = list(
        type = "object",
        properties = list(
          path_id = list(
            type = "string",
            enum = ontology$path_id
          ),
          confidence = list(
            type = "string",
            enum = c(
              "high",
              "medium",
              "low"
            )
          ),
          evidence = list(
            type = "string"
          )
        ),
        required = c(
          "path_id",
          "confidence",
          "evidence"
        ),
        additionalProperties = FALSE
      )
    ),
    review_required = list(
      type = "boolean"
    ),
    review_reason = list(
      type = c(
        "string",
        "null"
      )
    )
  ),
  required = c(
    "assignments",
    "review_required",
    "review_reason"
  ),
  additionalProperties = FALSE
)

extract_output_text <- function(response) {

  message_items <- response$output[
    vapply(
      response$output,
      function(item) {
        identical(
          item$type,
          "message"
        )
      },
      logical(1)
    )
  ]

  content_items <- unlist(
    lapply(
      message_items,
      function(item) {
        item$content
      }
    ),
    recursive = FALSE
  )

  text_items <- content_items[
    vapply(
      content_items,
      function(item) {
        identical(
          item$type,
          "output_text"
        ) &&
          !is.null(item$text)
      },
      logical(1)
    )
  ]

  if (length(text_items) == 0L) {
    stop(
      "No output_text item was returned."
    )
  }

  text_items[[1]]$text
}

classify_record <- function(
    sampling_stratum,
    record_sequence,
    record_id,
    title,
    abstract
) {

  user_prompt <- paste0(
    "ONTOLOGY\n\n",
    ontology_prompt,
    "\n\nRECORD\n\nTitle: ",
    title,
    "\n\nAbstract: ",
    abstract,
    "\n\nReturn only substantive ontology assignments."
  )

  body <- list(
    model = "gpt-5-mini",
    store = FALSE,
    reasoning = list(
      effort = "low"
    ),
    input = list(
      list(
        role = "system",
        content = list(
          list(
            type = "input_text",
            text = system_prompt
          )
        )
      ),
      list(
        role = "user",
        content = list(
          list(
            type = "input_text",
            text = user_prompt
          )
        )
      )
    ),
    text = list(
      verbosity = "low",
      format = list(
        type = "json_schema",
        name = "topic_v3_validation",
        strict = TRUE,
        schema = response_schema
      )
    )
  )

  parsed <- tryCatch(
    {
      response <- httr2::request(
        "https://api.openai.com/v1/responses"
      ) |>
        httr2::req_auth_bearer_token(
          api_key
        ) |>
        httr2::req_body_json(
          body,
          auto_unbox = TRUE
        ) |>
        httr2::req_timeout(
          180
        ) |>
        httr2::req_retry(
          max_tries = 3,
          backoff = ~ 2^.x
        ) |>
        httr2::req_perform() |>
        httr2::resp_body_json()

      jsonlite::fromJSON(
        extract_output_text(response),
        simplifyVector = FALSE
      )
    },
    error = function(e) {
      structure(
        list(
          message = conditionMessage(e)
        ),
        class = "classification_error"
      )
    }
  )

  if (inherits(
    parsed,
    "classification_error"
  )) {
    return(
      list(
        record = tibble::tibble(
          sampling_stratum = sampling_stratum,
          record_sequence = record_sequence,
          record_id = record_id,
          title = title,
          abstract = abstract,
          assigned_path_ids = NA_character_,
          assigned_paths = NA_character_,
          assignment_count = 0L,
          review_required = TRUE,
          review_reason = NA_character_,
          classification_failed = TRUE,
          classification_error = parsed$message
        ),
        long = tibble::tibble()
      )
    )
  }

  assignment_ids <- vapply(
    parsed$assignments,
    function(x) {
      x$path_id
    },
    character(1)
  )

  # Protect against duplicate IDs in a single response.
  assignment_ids <- unique(
    assignment_ids
  )

  assigned <- ontology |>
    dplyr::filter(
      path_id %in% assignment_ids
    ) |>
    dplyr::arrange(
      match(
        path_id,
        assignment_ids
      )
    )

  assignment_lookup <- parsed$assignments[
    !duplicated(
      vapply(
        parsed$assignments,
        function(x) {
          x$path_id
        },
        character(1)
      )
    )
  ]

  long <- if (
    length(assignment_lookup) == 0L
  ) {
    tibble::tibble()
  } else {
    tibble::tibble(
      sampling_stratum = sampling_stratum,
      record_sequence = record_sequence,
      record_id = record_id,
      title = title,
      abstract = abstract,
      path_id = vapply(
        assignment_lookup,
        function(x) {
          x$path_id
        },
        character(1)
      ),
      confidence = vapply(
        assignment_lookup,
        function(x) {
          x$confidence
        },
        character(1)
      ),
      evidence = vapply(
        assignment_lookup,
        function(x) {
          x$evidence
        },
        character(1)
      )
    ) |>
      dplyr::left_join(
        ontology |>
          dplyr::select(
            path_id,
            hierarchy_path
          ),
        by = "path_id"
      )
  }

  record <- tibble::tibble(
    sampling_stratum = sampling_stratum,
    record_sequence = record_sequence,
    record_id = record_id,
    title = title,
    abstract = abstract,
    assigned_path_ids = if (
      nrow(assigned) == 0L
    ) {
      NA_character_
    } else {
      paste(
        assigned$path_id,
        collapse = "; "
      )
    },
    assigned_paths = if (
      nrow(assigned) == 0L
    ) {
      NA_character_
    } else {
      paste(
        assigned$hierarchy_path,
        collapse = "; "
      )
    },
    assignment_count = nrow(assigned),
    review_required = parsed$review_required,
    review_reason = if (
      is.null(parsed$review_reason)
    ) {
      NA_character_
    } else {
      parsed$review_reason
    },
    classification_failed = FALSE,
    classification_error = NA_character_
  )

  list(
    record = record,
    long = long
  )
}

# -----------------------------------------------------------------------------
# Resume from checkpoint if available
# -----------------------------------------------------------------------------

if (file.exists(checkpoint_file)) {

  checkpoint <- readRDS(
    checkpoint_file
  )

  record_results <- checkpoint$record_results
  long_results <- checkpoint$long_results

  completed_ids <- unique(
    record_results$record_id
  )

  message(
    "Resuming from checkpoint: ",
    length(completed_ids),
    " / ",
    nrow(records),
    " records completed."
  )

} else {

  record_results <- tibble::tibble()
  long_results <- tibble::tibble()
  completed_ids <- character()

  message(
    "Starting new 50-record ontology v3 validation."
  )
}

remaining <- records |>
  dplyr::filter(
    !record_id %in% completed_ids
  )

if (nrow(remaining) == 0L) {
  message(
    "All validation records are already complete."
  )
}

for (i in seq_len(
  nrow(remaining)
)) {

  current <- remaining[i, ]

  message(
    "Classifying ",
    length(completed_ids) + i,
    " / ",
    nrow(records),
    ": record_id ",
    current$record_id
  )

  result <- classify_record(
    sampling_stratum = current$sampling_stratum,
    record_sequence = current$record_sequence,
    record_id = current$record_id,
    title = current$title,
    abstract = current$abstract
  )

  record_results <- dplyr::bind_rows(
    record_results,
    result$record
  )

  long_results <- dplyr::bind_rows(
    long_results,
    result$long
  )

  saveRDS(
    list(
      record_results = record_results,
      long_results = long_results
    ),
    checkpoint_file
  )

  readr::write_csv(
    record_results |>
      dplyr::arrange(
        record_sequence
      ),
    record_output_file,
    na = ""
  )

  readr::write_csv(
    long_results |>
      dplyr::arrange(
        record_sequence,
        path_id
      ),
    long_output_file,
    na = ""
  )

  failures <- record_results |>
    dplyr::filter(
      classification_failed
    )

  readr::write_csv(
    failures,
    failure_file,
    na = ""
  )
}

message("")
message("Ontology v3 LLM validation completed.")
message(
  "Records: ",
  nrow(record_results)
)
message(
  "Failures: ",
  sum(
    record_results$classification_failed
  )
)
message(
  "Record output: ",
  record_output_file
)
message(
  "Long output: ",
  long_output_file
)
message("")
message(
  "Next run: source(\"scripts/44_compare_topic_v3_validation.R\")"
)
